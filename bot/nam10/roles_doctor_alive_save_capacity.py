"""ظرفیت نجات پزشک بر اساس تعداد بازیکنان زنده — مذاکره و ماسون."""

from __future__ import annotations

DOCTOR_ALIVE_CAPACITY_DESCRIPTION_BODY_FA = (
    "پزشک عضو تیم شهروندان است. هر شب می‌تواند بر اساس تعداد بازیکنان زنده، "
    "یک یا چند نفر را از شات مافیا نجات دهد: اگر ۷ نفر یا کمتر زنده باشند ۱ نفر، "
    "اگر ۸ تا ۱۱ نفر زنده باشند ۲ نفر، اگر ۱۲ تا ۱۵ نفر زنده باشند ۳ نفر، "
    "و اگر ۱۶ نفر یا بیشتر زنده باشند ۴ نفر را می‌تواند نجات دهد. "
    "پزشک می‌تواند خودش را هم نجات دهد، اما در کل بازی فقط دو بار اجازه نجات خودش را دارد."
)


def doctor_save_capacity_for_alive_count(alive_players: int) -> int:
    """ظرفیت نجات در یک شب — فقط بر اساس تعداد زنده در لحظهٔ ارسال پنل."""
    if alive_players <= 7:
        return 1
    if alive_players <= 11:
        return 2
    if alive_players <= 15:
        return 3
    return 4
