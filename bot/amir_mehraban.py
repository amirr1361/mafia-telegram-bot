def bazpors_rolehelp_html(role: Role) -> str:
    """متن راهنمای نقش برای بازیکن (HTML)."""
    mapping: dict[Role, str] = {
        Role.MAFIA_BOSS: _doc_mafia_boss(),
        Role.NATO: _doc_nato(),
        Role.SHIAD: _doc_shiad(),
        Role.DETECTIVE: _doc_detective(),
        Role.DOCTOR: _doc_doctor(),
        Role.RUINTAN: _doc_ruintan(),
        Role.INTERROGATOR: _doc_interrogator(),
        Role.HUNTER: _doc_hunter(),
        Role.MAFIA_BASIC: _AMIR_HOST_DOCS["mafia_basic"],
        Role.CITIZEN: _AMIR_HOST_DOCS["citizen"],
        Role.SNIPER: _AMIR_HOST_DOCS["sniper"],
    }
    return mapping.get(role, _doc_generic(role.value))


def amir_host_keyboard() -> list[list[tuple[str, str]]]:
    """ردیف‌های (key, دکمه) برای ساخت اینلاین."""
    keys = list(AMIR_HOST_ROLE_KEYS)
    rows: list[list[tuple[str, str]]] = []
    row: list[tuple[str, str]] = []
    for k, label in keys:
        row.append((k, label))
        if len(row) >= 2:
            rows.append(row)
            row = []
    if row:
        rows.append(row)
    return rows
