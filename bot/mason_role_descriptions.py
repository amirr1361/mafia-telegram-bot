MASON_CARD_HINT_TEXT = (
    "برای دیدن کارت نقش روی تصویر محو بزنید؛ "
    "برای دیدن نام نقش روی نوار خاکستری زیر بزنید."
)


def mason_role_description_fa(role: Role) -> str:
    return MASON_ROLE_DESCRIPTIONS_FA.get(role, "")


def build_mason_private_role_message_html(role: Role) -> str:
    """کل متن نقش داخل یک اسپویلر تلگرام."""
    body = mason_role_description_fa(role)
    if not body:
        body = f"🎭 نقش شما: {role.value}"
    return f"<tg-spoiler>{html.escape(body)}</tg-spoiler>"
